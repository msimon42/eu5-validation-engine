"""Assemble inactive CK3 review files; never merge, install or activate content."""
from __future__ import annotations

import base64
import binascii
import re
import unicodedata

from .safety import check_path_collisions, sha256_bytes, validate_relative_path

INSTRUCTIONS_PATH = "CK3_BUNDLE_INSTRUCTIONS.txt"
_HASH = re.compile(r"^[a-f0-9]{64}$")


def _quoted(value: str, field: str, limit: int) -> str:
    if (not isinstance(value, str) or not value.strip() or len(value) > limit
            or any(ord(character) < 32 or ord(character) == 127 for character in value)):
        raise ValueError(f"{field} must be an explicit bounded single-line string")
    try:
        value.encode("utf-8")
    except UnicodeEncodeError as exc:
        raise ValueError(f"{field} must contain valid Unicode") from exc
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _record(path: str, raw: bytes) -> dict:
    return {"path": path, "bytes_base64": base64.b64encode(raw).decode(), "sha256": sha256_bytes(raw)}


def _portable_paths(paths: list[str]) -> None:
    check_path_collisions(paths)
    seen = set()
    for path in paths:
        key = unicodedata.normalize("NFC", path).casefold()
        if key in seen:
            raise ValueError("portable Unicode path collision")
        seen.add(key)
    for key in seen:
        parts = key.split("/")
        if any("/".join(parts[:number]) in seen for number in range(1, len(parts))):
            raise ValueError("file and directory paths collide")


def ck3_bundle_files(generated_files: list[dict], *, mod_directory: str, name: str,
                     supported_version: str) -> list[dict]:
    """Return exact output records for a reviewed CK3 patch folder and .mod file.

    ``mod_directory`` is a portable single folder name. ``supported_version`` is
    explicitly supplied from the selected target; this function never invents
    versions or converts an advisory bundle into a compatibility claim. No
    source package identity, Workshop ID, dependencies or replacement masks are
    copied into the fresh descriptor.
    """
    folder = validate_relative_path(mod_directory)
    if (folder != mod_directory or "/" in folder or folder.startswith(".")
            or folder.casefold() == INSTRUCTIONS_PATH.casefold()):
        raise ValueError("mod_directory must be one portable visible folder name")
    quoted_name = _quoted(name, "name", 200)
    quoted_version = _quoted(supported_version, "supported_version", 100)
    if not isinstance(generated_files, list) or not generated_files or len(generated_files) > 4096:
        raise ValueError("a bounded nonempty generated file set is required")
    result, total = [], 0
    for item in generated_files:
        if not isinstance(item, dict):
            raise ValueError("generated files must be exact file records")
        path = validate_relative_path(item.get("path"))
        if path != item["path"]:
            raise ValueError("generated paths must use portable forward slashes")
        parts = path.casefold().split("/")
        if ".metadata" in parts or parts[-1].endswith(".mod"):
            raise ValueError("source descriptors and EU5 metadata cannot enter a CK3 patch bundle")
        encoded, expected = item.get("bytes_base64"), item.get("sha256")
        if not isinstance(encoded, str) or not isinstance(expected, str) or not _HASH.fullmatch(expected):
            raise ValueError("generated files require canonical base64 and an exact SHA-256")
        if len(encoded) > 45_000_000:
            raise ValueError("generated file byte budget exceeded")
        try:
            raw = base64.b64decode(encoded, validate=True)
        except (ValueError, binascii.Error) as exc:
            raise ValueError("invalid generated file base64") from exc
        if base64.b64encode(raw).decode() != encoded or sha256_bytes(raw) != expected:
            raise ValueError("generated bytes differ from their canonical base64 or declared hash")
        total += len(raw)
        if len(raw) > 32 * 1024 * 1024 or total > 128 * 1024 * 1024:
            raise ValueError("generated file byte budget exceeded")
        result.append(_record(folder + "/" + path, raw))
    descriptor = f"name={quoted_name}\nsupported_version={quoted_version}\n".encode("utf-8")
    result.append(_record(folder + "/descriptor.mod", descriptor))
    result.append(_record(folder + ".mod", descriptor + f'path="mod/{folder}"\n'.encode("utf-8")))
    instructions = (
        "CK3 experimental review bundle\n\n"
        "This bundle is inactive and unvalidated. No launcher playset or active release was changed.\n"
        "The supported_version descriptor field records the explicit selected version; it is not proof of compatibility.\n"
        f"For a later manual installation, {folder}/ and {folder}.mod belong together in the CK3 user-data mod/ folder.\n"
        "Review the generated files and preservation requirements before any manual launcher activation.\n"
    ).encode("utf-8")
    result.append(_record(INSTRUCTIONS_PATH, instructions))
    _portable_paths([item["path"] for item in result])
    return result
