"""Generate transport schemas and TypeScript request types from Python models."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from backend.app.contracts import PAYLOADS
from backend.app.main import Command, create_app
from backend.agent.contracts import AgentRequest, MODELS as AGENT_PAYLOADS

ROOT = Path(__file__).resolve().parents[1]


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null", "object": "Record<string, unknown>"}.get(kind, "unknown")


def outputs():
    schemas = {name: model.model_json_schema() for name, model in PAYLOADS.items()}
    definitions = {}
    for schema in schemas.values():
        definitions.update(schema.get("$defs", {}))
        definitions[schema["title"]] = schema
    lines = ["// Generated by scripts/generate_contracts.py. Do not edit."]
    for name, schema in sorted(definitions.items()):
        required = schema.get("required", [])
        lines.append(f"export interface {name} {{")
        for key, field in schema.get("properties", {}).items():
            lines.append(f"  {key}{'' if key in required else '?'}: {ts_type(field)};")
        lines.append("}")
    lines.append("export type CommandKind = " + " | ".join(json.dumps(name) for name in PAYLOADS) + ";")
    lines.append("export type CommandRequest = " + "\n  | ".join(
        f"{{ command: {json.dumps(name)}; workspace_id?: string; payload: {model.__name__}; idempotency_key: string; expected_revision?: number }}" for name, model in PAYLOADS.items()) + ";")
    return {
        ROOT / "schemas" / "commands-v1.json": json.dumps({"schema_version": 1, "envelope": Command.model_json_schema(), "payloads": schemas}, indent=2) + "\n",
        ROOT / "schemas" / "openapi.json": json.dumps(create_app().openapi(), indent=2) + "\n",
        ROOT / "schemas" / "agent-v3.json": json.dumps({"schema_version": 3,
            "envelope": AgentRequest.model_json_schema(),
            "payloads": {name: model.model_json_schema() for name, model in AGENT_PAYLOADS.items()}}, indent=2) + "\n",
        ROOT / "frontend" / "src" / "generated" / "contracts.ts": "\n".join(lines) + "\n",
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Contract drift: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
