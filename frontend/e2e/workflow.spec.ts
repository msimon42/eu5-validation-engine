import fs from 'node:fs';
import path from 'node:path';
import { test, expect, hashTree, expectInactive, importAndScan, stage, validate, commandResult } from './fixtures';

test('disk mods → real UI → repair → validation → exact ZIP; originals and activation stay untouched', async ({ page, app }, testInfo) => {
  const fixture = app.fixture('F03');
  const original = hashTree(fixture.fixture_path);
  const { workspaceId, scan } = await importAndScan(page, app, fixture);
  expect(scan.analysis.summary.files).toBe(3);
  expect(scan.analysis.obligations.find((entry: { owner: string }) => entry.owner === 'A').state).toBe('violated');
  await page.getByRole('button', { name: 'Investigation', exact: true }).click();
  await expect(page.getByRole('tabpanel')).toContainText('REPLACE:item = { x = 2 y = 1 }');
  await expect(page.getByRole('tabpanel')).toContainText('REPLACE:item = { x = 1 y = 3 }');
  const staged = await stage(page);
  expect(staged.status).toBe('staged');
  await page.getByRole('tab', { name: 'Staged diff', exact: true }).click();
  await expect(page.getByRole('tabpanel')).toContainText('REPLACE:item = { x = 2 y = 3 }');
  await page.getByRole('button', { name: 'Validation & release', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Export experimental bundle', exact: true })).toBeDisabled();
  const validated = await validate(page);
  expect(validated.validation.experimental_eligible).toBe(true);
  expect(validated.validation.validated_promotion_eligible).toBe(false);
  expect(validated.validation.obligations.every((entry: { state: string }) => entry.state === 'satisfied')).toBe(true);
  await expect(page.getByRole('button', { name: 'Promotion unavailable', exact: true })).toBeDisabled();
  const exported = await commandResult(page, 'export', () => page.getByRole('button', { name: 'Export experimental bundle', exact: true }).click());
  expect(exported.result.job.state).toBe('completed');
  const downloaded = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download bundle', exact: true }).click();
  const download = await downloaded;
  const filename = testInfo.outputPath('experimental-bundle.zip');
  await download.saveAs(filename);
  const bundle = app.inspectZip(filename);
  expect(bundle.manifest.kind).toBe('experimental_bundle');
  expect(bundle.manifest.activated).toBe(false);
  const generated = Object.entries(bundle.files).filter(([name]) => name.endsWith('.txt'));
  expect(generated).toHaveLength(1);
  expect(Buffer.from(generated[0][1].bytes_base64, 'base64').toString('utf8')).toBe('REPLACE:item = { x = 2 y = 3 }\n');
  for (const file of bundle.manifest.files) expect(bundle.files[`files/${file.path}`].sha256).toBe(file.sha256);
  expect(hashTree(fixture.fixture_path)).toEqual(original);
  expectInactive(app);
  await page.reload();
  await expect(page.getByRole('combobox', { name: 'Current workspace' })).toHaveValue(workspaceId);
  await page.getByRole('button', { name: 'Validation & release', exact: true }).click();
  await expect(page.getByRole('heading', { name: staged.candidate_id, exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Export experimental bundle', exact: true })).toBeEnabled();
  await page.screenshot({ path: testInfo.outputPath('validated-workflow.png'), fullPage: true });
});

test('a genuine conflict requires an explicit scoped design choice before export', async ({ page, app }) => {
  const fixture = app.fixture('F04');
  const original = hashTree(fixture.fixture_path);
  await importAndScan(page, app, fixture);
  expect((await stage(page)).status).toBe('blocked');
  await page.getByRole('button', { name: 'Design decisions', exact: true }).click();
  for (const radio of await page.getByRole('radio').all()) await expect(radio).not.toBeChecked();
  const save = page.getByRole('button', { name: 'Save scoped decision', exact: true });
  await expect(save).toBeDisabled();
  await page.getByRole('radio', { name: /Retain mod B/ }).check();
  await expect(save).toBeDisabled();
  await page.getByLabel('Why this outcome?', { exact: true }).fill('Keep B at 5 and waive only A’s contradictory x target.');
  await commandResult(page, 'decision', () => save.click());
  await expect(page.getByText('Scoped decision recorded.', { exact: false })).toBeVisible();
  expect((await stage(page)).status).toBe('staged');
  const result = await validate(page);
  expect(result.validation.experimental_eligible).toBe(true);
  const waived = result.validation.obligations.filter((entry: { state: string }) => entry.state === 'waived_by_user');
  expect(waived).toHaveLength(1);
  expect(waived[0].owner).toBe('A');
  expect(waived[0].decision_id).toBeTruthy();
  expect(hashTree(fixture.fixture_path)).toEqual(original);
  expectInactive(app);
});

