import path from 'node:path';
import { test, expect, hashTree, expectInactive, commandResult } from './fixtures';

test('CK3 disk playset → discovery → import → advisory inspection; originals and launcher state stay untouched', async ({ page, app }, testInfo) => {
  const fixture = app.ck3Fixture();
  const originals = hashTree(fixture.root);
  await page.goto(app.url);
  await page.getByRole('button', { name: 'New workspace', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Workspace name', { exact: true }).fill('Synthetic CK3 browser stack');
  await dialog.getByRole('combobox', { name: 'Game', exact: true }).selectOption('ck3');
  await dialog.getByRole('combobox', { name: 'Target platform', exact: true }).selectOption(fixture.platform);
  const created = await commandResult(page, 'create_workspace', () => dialog.getByRole('button', { name: 'Create workspace', exact: true }).click());
  expect(created.submitted.payload).toMatchObject({ game_id: 'ck3', target_platform: fixture.platform, mode: 'game' });
  const workspaceId = created.result.workspace_id as string;
  await expect(page.getByRole('combobox', { name: 'Current workspace' })).toHaveValue(workspaceId);
  await page.getByRole('button', { name: 'Discover CK3 playsets', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByText('Location overrides (optional)', { exact: true }).click();
  await dialog.getByLabel('CK3 installation directory', { exact: true }).fill(fixture.installation);
  await dialog.getByLabel('CK3 user-data directory', { exact: true }).fill(fixture.user_data);
  await dialog.getByLabel('Steam directories', { exact: true }).fill(fixture.steam);
  const discovered = await commandResult(page, 'discover_ck3', () => dialog.getByRole('button', { name: 'Discover CK3', exact: true }).click());
  expect(discovered.result.job.state, JSON.stringify(discovered.result.job)).toBe('completed');
  expect(discovered.result.discovery.complete, JSON.stringify(discovered.result.discovery.diagnostics)).toBe(true);
  expect(discovered.result.discovery.playset).toEqual(fixture.active_order);
  expect(discovered.result.discovery.capabilities.executed_game_evidence).toBe(false);
  await dialog.getByLabel('Launcher playset', { exact: true }).selectOption('alternate');
  const importButton = dialog.getByRole('button', { name: 'Import for inspection', exact: true });
  await expect(importButton).toBeDisabled();
  const alternate = await commandResult(page, 'discover_ck3', () => dialog.getByRole('button', { name: 'Rediscover selected playset', exact: true }).click());
  expect(alternate.submitted.payload.playset_id).toBe('alternate');
  expect(alternate.result.discovery.playset).toEqual(fixture.alternate_order);
  await expect(importButton).toBeEnabled();
  const imported = await commandResult(page, 'import_ck3', () => importButton.click());
  expect(imported.result.workspace.default_playset).toEqual(fixture.alternate_order);
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Scan playset', exact: true }).click();
  dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel('Enabled playset order', { exact: true })).toHaveValue(fixture.alternate_order.join(', '));
  await expect(dialog.getByRole('tab', { name: 'Contract fixture', exact: true })).toHaveCount(0);
  const scanned = await commandResult(page, 'scan', () => dialog.getByRole('button', { name: 'Capture & scan', exact: true }).click());
  expect(scanned.result.job.state, JSON.stringify(scanned.result.job)).toBe('completed');
  const scan = await (await page.request.get(`${app.url}/api/scans/${scanned.result.scan_id}`)).json();
  expect(scan.game_id).toBe('ck3');
  expect(scan.playset).toEqual(fixture.alternate_order);
  expect(scan.analysis.findings.some((finding: { kind: string }) => finding.kind === 'duplicate_definition')).toBe(true);
  expect(scan.analysis.findings.some((finding: { kind: string }) => finding.kind === 'overlapping_path')).toBe(true);
  expect(scan.analysis.definitions.every((definition: { state: string }) => definition.state === 'unknown')).toBe(true);
  expect(scan.analysis.files.some((file: { path: string }) => file.path === 'events/nested/fixture_events.txt')).toBe(true);
  expect(scan.analysis.files.some((file: { path: string; kind: string }) => file.path === 'gfx/interface/fixture.dds' && file.kind === 'opaque')).toBe(true);
  await expect(page.getByText('Duplicate definition', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Investigation', exact: true }).click();
  const trait = page.getByRole('button', { name: /game\/trait\/shared_trait/ });
  await trait.click();
  await expect(page.getByRole('tabpanel')).toContainText('shared_trait = { diplomacy = 2 }');
  await expect(page.getByRole('tabpanel')).toContainText('shared_trait = { diplomacy = 3 }');
  await expect(page.getByRole('button', { name: 'Stage proposal', exact: true }).first()).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Replay investigation', exact: true })).toBeDisabled();
  await page.getByRole('tab', { name: 'Effective result', exact: true }).click();
  await expect(page.getByRole('tabpanel')).toContainText('"state": "unknown"');
  await page.getByRole('button', { name: 'Validation & release', exact: true }).click();
  await expect(page.getByText('CK3 repair capability is not qualified', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Validate full playset', exact: true })).toBeDisabled();
  expect(hashTree(fixture.root)).toEqual(originals);
  expect(hashTree(path.join(app.state, 'artifacts'))).toEqual({});
  expectInactive(app);
  await page.screenshot({ path: testInfo.outputPath('ck3-inspection.png'), fullPage: true });
});
